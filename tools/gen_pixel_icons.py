"""Builds frontend/js/pixelIconData.js from the pixelarticons npm package.

pixelarticons (MIT, https://github.com/halfmage/pixelarticons) ships ~1000 SVGs; the
app only needs a few dozen, so this copies just the ones listed in ICONS into one
small JS module instead of vendoring the whole package.

To add an icon: put its name in ICONS (browse names in the package's svg/ folder,
or at https://pixelarticons.com), then re-run:

    npm pack pixelarticons@2.4.2          # produces pixelarticons-2.4.2.tgz
    python tools/gen_pixel_icons.py pixelarticons-2.4.2.tgz

The package's MIT license is copied to frontend/licenses/ alongside the output.
"""
import json
import pathlib
import re
import sys
import tarfile

ICONS = [
    "close", "plus", "download", "moon", "sun", "user",
    "message-text", "list-box", "chart-bar-big", "settings-cog",
    "languages", "globe", "bell", "map-pin", "card-text", "target", "undo",
    "arrow-left", "trash",
]

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_JS = ROOT / "frontend" / "js" / "pixelIconData.js"
OUT_LICENSE = ROOT / "frontend" / "licenses" / "pixelarticons-LICENSE.txt"


def inner_markup(svg_text: str) -> str:
    """Everything between <svg ...> and </svg>, whitespace-collapsed."""
    match = re.search(r"<svg\b[^>]*>(.*)</svg>", svg_text, re.S)
    if not match:
        raise ValueError("not an <svg> document")
    return re.sub(r"\s+", " ", match.group(1)).strip()


def main(tgz_path: str) -> None:
    archive = tarfile.open(tgz_path)
    icons = {}
    for name in ICONS:
        member = archive.extractfile(f"package/svg/{name}.svg")
        if member is None:
            raise SystemExit(f"icon not found in package: {name}")
        icons[name] = inner_markup(member.read().decode("utf-8"))

    version = json.load(archive.extractfile("package/package.json"))["version"]
    lines = [
        "// GENERATED by tools/gen_pixel_icons.py — do not edit by hand.",
        f"// Source: pixelarticons {version} (MIT) https://github.com/halfmage/pixelarticons",
        "// All icons are drawn on a 24x24 grid with fill=currentColor.",
        "export const PIXELARTICONS = {",
    ]
    lines += [f"    {json.dumps(name)}: {json.dumps(markup)}," for name, markup in icons.items()]
    lines.append("};")
    OUT_JS.write_text("\n".join(lines) + "\n", encoding="utf-8")

    OUT_LICENSE.parent.mkdir(parents=True, exist_ok=True)
    OUT_LICENSE.write_bytes(archive.extractfile("package/LICENSE").read())
    print(f"wrote {OUT_JS.relative_to(ROOT)} ({len(icons)} icons, pixelarticons {version})")
    print(f"wrote {OUT_LICENSE.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
